# 安装/卸载 share-site 的「登录时自动启动」（用户级，不需要管理员）
# 机制：Startup 文件夹快捷方式 → wscript → 隐藏窗口运行启动脚本
#
# 用法：
#   powershell -ExecutionPolicy Bypass -File scripts\install-autostart.ps1
#   powershell -ExecutionPolicy Bypass -File scripts\install-autostart.ps1 -Uninstall
#   powershell -ExecutionPolicy Bypass -File scripts\install-autostart.ps1 -StartNow
#
# 默认启动的是仓库里的 server\start-share-site.ps1，可以用 -Script 指向别处。

param(
    [string]$Script = (Join-Path (Split-Path -Parent $PSScriptRoot) 'server\start-share-site.ps1'),
    [switch]$Uninstall,
    [switch]$StartNow
)

$ErrorActionPreference = 'Stop'

$name = 'QuniteZone Share Site'
$startupDir = [Environment]::GetFolderPath('Startup')
$autostartDir = Join-Path $env:LOCALAPPDATA 'QuniteZone\autostart'
$vbsName = 'start-share-site.vbs'
$lnkPath = Join-Path $startupDir ($name + '.lnk')

if ($Uninstall) {
    if (Test-Path $lnkPath) {
        Remove-Item $lnkPath -Force
        Write-Host ('[autostart] 已移除快捷方式：{0}' -f $lnkPath)
    } else {
        Write-Host ('[autostart] 未安装：{0}' -f $name)
    }
    exit 0
}

if (-not (Test-Path $Script)) {
    throw ('启动脚本不存在：{0}' -f $Script)
}

New-Item -ItemType Directory -Force $autostartDir | Out-Null

# 用 wscript 启动，窗口完全隐藏；先等 15 秒，避开登录瞬间的资源竞争
$vbs = @"
' Generated by install-autostart.ps1 - do not edit
WScript.Sleep 15000
Set sh = CreateObject("WScript.Shell")
sh.Run "powershell.exe -NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File ""$Script""", 0, False
"@
$vbsPath = Join-Path $autostartDir $vbsName
[IO.File]::WriteAllText($vbsPath, $vbs.Replace("`r`n", "`n"), (New-Object System.Text.ASCIIEncoding))

$ws = New-Object -ComObject WScript.Shell
$lnk = $ws.CreateShortcut($lnkPath)
$lnk.TargetPath = "$env:WINDIR\System32\wscript.exe"
$lnk.Arguments = '"{0}"' -f $vbsPath
$lnk.WorkingDirectory = $autostartDir
$lnk.WindowStyle = 7
$lnk.Description = ('登录时自动启动：' + $Script)
$lnk.Save()

Write-Host ('[autostart] 已安装：{0}' -f $lnkPath)
Write-Host ('             → {0}' -f $Script)

if ($StartNow) {
    Start-Process -FilePath "$env:WINDIR\System32\wscript.exe" -ArgumentList ('"{0}"' -f $vbsPath) -WindowStyle Hidden
    Write-Host ('[autostart] 已触发一次（15 秒后生效）')
}
